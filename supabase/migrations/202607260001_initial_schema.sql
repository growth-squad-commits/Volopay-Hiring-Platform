create or replace function private.guard_candidate_update()
returns trigger language plpgsql security invoker set search_path = ''
as $$
declare a public.assessments;
begin
  if (select private.is_admin()) then new.updated_at=now(); return new; end if;
  if not (select private.candidate_email_matches(old.email)) then raise exception 'Not authorized'; end if;
  if new.assessment_id is distinct from old.assessment_id or new.email is distinct from old.email or new.full_name is distinct from old.full_name
     or new.score is distinct from old.score or new.decision is distinct from old.decision then raise exception 'Protected fields cannot be changed'; end if;
  select * into a from public.assessments where id=old.assessment_id;
  if old.status='not_started' and new.status='in_progress' then
    if a.status<>'published' or now()<a.available_from or now()>a.available_until then raise exception 'Assessment unavailable'; end if;
    new.auth_user_id=(select auth.uid()); new.started_at=now(); new.expires_at=least(a.available_until,now()+make_interval(mins=>a.duration_minutes)); new.last_saved_at=now();
  elsif old.status='in_progress' and new.status='submitted' then
    if now()>old.expires_at then raise exception 'Assessment time expired'; end if;
    new.submitted_at=now(); new.last_saved_at=now();
  elsif new.status is distinct from old.status then raise exception 'Invalid status transition';
  end if;
  new.updated_at=now(); return new;
end; $$;
drop trigger if exists guard_candidate_update on public.candidates;
create trigger guard_candidate_update before update on public.candidates for each row execute function private.guard_candidate_update();

