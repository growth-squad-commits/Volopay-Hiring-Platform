create schema if not exists private;

create table if not exists public.admin_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  full_name text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.assessments (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  instructions text not null default '',
  status text not null default 'draft' check (status in ('draft','published','closed')),
  duration_minutes integer not null default 45 check (duration_minutes between 1 and 1440),
  total_points integer not null default 100 check (total_points >= 0),
  available_from timestamptz not null,
  available_until timestamptz not null,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (available_until > available_from)
);

create table if not exists public.assessment_questions (
  id bigint generated by default as identity primary key,
  assessment_id bigint not null references public.assessments(id) on delete cascade,
  title text not null,
  prompt text not null,
  points integer not null default 0 check (points >= 0),
  sort_order integer not null default 0,
  response_type text not null default 'written' check (response_type in ('written','link','file_upload')),
  is_required boolean not null default true,
  written_answer_type text check (written_answer_type in ('short','long')),
  word_limit integer,
  allowed_file_types text[],
  maximum_file_size_mb integer,
  link_guidance text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.candidates (
  id bigint generated by default as identity primary key,
  assessment_id bigint not null references public.assessments(id) on delete cascade,
  auth_user_id uuid references auth.users(id) on delete set null,
  full_name text not null,
  email text not null,
  phone text,
  status text not null default 'not_started' check (status in ('not_started','in_progress','submitted','reviewed')),
  score numeric,
  decision text not null default 'pending' check (decision in ('pending','shortlisted','on_hold','rejected')),
  started_at timestamptz,
  expires_at timestamptz,
  submitted_at timestamptz,
  last_saved_at timestamptz,
  source text not null default 'manual',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (assessment_id, email)
);

create table if not exists public.candidate_responses (
  id bigint generated by default as identity primary key,
  candidate_id bigint not null references public.candidates(id) on delete cascade,
  question_id bigint not null references public.assessment_questions(id) on delete cascade,
  response_text text,
  response_url text,
  file_path text,
  file_name text,
  file_size bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (candidate_id, question_id)
);

create index if not exists candidates_assessment_id_idx on public.candidates(assessment_id);
create index if not exists candidates_auth_user_id_idx on public.candidates(auth_user_id);
create index if not exists candidates_email_idx on public.candidates(lower(email));
create index if not exists assessment_questions_assessment_id_idx on public.assessment_questions(assessment_id);
create index if not exists candidate_responses_candidate_id_idx on public.candidate_responses(candidate_id);
create index if not exists candidate_responses_question_id_idx on public.candidate_responses(question_id);

