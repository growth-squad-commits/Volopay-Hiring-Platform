create or replace function private.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$ select exists(select 1 from public.admin_profiles p where p.user_id = (select auth.uid()) and p.is_active); $$;
revoke all on function private.is_admin() from public;
grant execute on function private.is_admin() to authenticated;

create or replace function private.candidate_email_matches(candidate_email text)
returns boolean language sql stable security invoker set search_path = ''
as $$ select (select auth.uid()) is not null and lower(coalesce((select auth.jwt()->>'email'),'')) = lower(candidate_email); $$;
revoke all on function private.candidate_email_matches(text) from public;
grant execute on function private.candidate_email_matches(text) to authenticated;

