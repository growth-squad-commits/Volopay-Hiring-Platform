create or replace function public.finalize_exam_attempt_internal(
  p_attempt_id uuid,
  p_reason text
)
returns public.exam_attempts
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_attempt public.exam_attempts;
  v_status text;
begin
  if p_reason not in ('manual', 'timeout') then
    raise exception 'Invalid submission reason';
  end if;

  select *
  into v_attempt
  from public.exam_attempts
  where id = p_attempt_id
  for update;

  if not found then
    raise exception 'Attempt not found';
  end if;

  if v_attempt.status <> 'in_progress' then
    return v_attempt;
  end if;

  v_status := case when p_reason = 'timeout' then 'auto_submitted' else 'submitted' end;

  update public.exam_attempts
  set
    status = v_status,
    submission_reason = p_reason,
    submitted_at = clock_timestamp(),
    updated_at = clock_timestamp()
  where id = p_attempt_id
  returning * into v_attempt;

  perform set_config('app.phase4_internal', 'on', true);
  update public.candidates
  set
    status = 'submitted',
    submitted_at = v_attempt.submitted_at,
    last_saved_at = coalesce(last_saved_at, v_attempt.submitted_at),
    updated_at = v_attempt.submitted_at
  where id = v_attempt.candidate_id
    and status in ('not_started', 'in_progress');

  insert into public.grading_queue(attempt_id, assessment_id, candidate_id)
  values (v_attempt.id, v_attempt.assessment_id, v_attempt.candidate_id)
  on conflict (attempt_id) do nothing;

  return v_attempt;
end;
$$;

revoke all on function public.finalize_exam_attempt_internal(uuid, text) from public, anon, authenticated;
grant execute on function public.finalize_exam_attempt_internal(uuid, text) to service_role;

create or replace function public.start_exam_attempt_internal(
  p_candidate_id bigint,
  p_student_id uuid,
  p_email text
)
returns table (
  attempt_id uuid,
  candidate_id bigint,
  assessment_id bigint,
  attempt_status text,
  started_at timestamptz,
  ends_at timestamptz,
  server_time timestamptz
)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_candidate public.candidates;
  v_assessment public.assessments;
  v_attempt public.exam_attempts;
  v_now timestamptz := clock_timestamp();
  v_closes_at timestamptz;
begin
  select *
  into v_candidate
  from public.candidates
  where id = p_candidate_id
  for update;

  if not found
    or v_candidate.auth_user_id is distinct from p_student_id
    or lower(v_candidate.email) <> lower(trim(p_email))
    or v_candidate.is_active is not true
    or (v_candidate.access_expires_at is not null and v_candidate.access_expires_at <= v_now)
  then
    raise exception 'Candidate assignment is unavailable';
  end if;

  select *
  into v_assessment
  from public.assessments
  where id = v_candidate.assessment_id;

  v_closes_at := coalesce(v_assessment.available_until, v_assessment.due_date);

  select *
  into v_attempt
  from public.exam_attempts a
  where a.candidate_id = p_candidate_id;

  if found then
    if v_attempt.status = 'in_progress' and v_now >= v_attempt.ends_at then
      v_attempt := public.finalize_exam_attempt_internal(v_attempt.id, 'timeout');
    end if;
    return query select
      v_attempt.id,
      v_attempt.candidate_id,
      v_attempt.assessment_id,
      v_attempt.status,
      v_attempt.started_at,
      v_attempt.ends_at,
      v_now;
    return;
  end if;

  if v_candidate.status <> 'not_started'
    or v_assessment.status <> 'published'
    or (v_assessment.available_from is not null and v_now < v_assessment.available_from)
    or v_closes_at is null
    or v_now >= v_closes_at
  then
    raise exception 'Assessment is not available to start';
  end if;

  insert into public.exam_attempts(
    candidate_id,
    assessment_id,
    student_id,
    started_at,
    ends_at
  )
  values (
    v_candidate.id,
    v_candidate.assessment_id,
    p_student_id,
    v_now,
    least(
      v_closes_at,
      v_now + make_interval(mins => v_assessment.duration_minutes)
    )
  )
  returning * into v_attempt;

  perform set_config('app.phase4_internal', 'on', true);
  update public.candidates
  set
    status = 'in_progress',
    started_at = v_attempt.started_at,
    expires_at = v_attempt.ends_at,
    last_saved_at = v_attempt.started_at,
    updated_at = v_attempt.started_at
  where id = v_candidate.id;

  return query select
    v_attempt.id,
    v_attempt.candidate_id,
    v_attempt.assessment_id,
    v_attempt.status,
    v_attempt.started_at,
    v_attempt.ends_at,
    v_now;
end;
$$;

