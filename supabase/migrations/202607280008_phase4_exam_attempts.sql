create or replace function public.auto_submit_expired_attempts()
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_count integer;
begin
  perform set_config('app.phase4_internal', 'on', true);

  with due as (
    select id
    from public.exam_attempts
    where status = 'in_progress'
      and ends_at <= clock_timestamp()
    order by ends_at
    limit 500
    for update skip locked
  ),
  expired as (
    update public.exam_attempts a
    set
      status = 'auto_submitted',
      submission_reason = 'timeout',
      submitted_at = clock_timestamp(),
      updated_at = clock_timestamp()
    from due
    where a.id = due.id
    returning a.id, a.assessment_id, a.candidate_id, a.submitted_at
  ),
  updated_candidates as (
    update public.candidates c
    set
      status = 'submitted',
      submitted_at = e.submitted_at,
      last_saved_at = coalesce(c.last_saved_at, e.submitted_at),
      updated_at = e.submitted_at
    from expired e
    where c.id = e.candidate_id
      and c.status in ('not_started', 'in_progress')
    returning e.id, e.assessment_id, e.candidate_id
  ),
  queued as (
    insert into public.grading_queue(attempt_id, assessment_id, candidate_id)
    select id, assessment_id, candidate_id
    from updated_candidates
    on conflict (attempt_id) do nothing
    returning id
  )
  select count(*) into v_count from expired;

  return v_count;
end;
$$;

revoke all on function public.auto_submit_expired_attempts() from public, anon, authenticated;
grant execute on function public.auto_submit_expired_attempts() to service_role;

-- Existing candidate guards remain useful for admin edits. Phase 4's
-- transactional functions set a transaction-local marker for internal updates.
create or replace function private.guard_candidate_update()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if current_setting('app.phase4_internal', true) = 'on' then
    new.updated_at = coalesce(new.updated_at, now());
    return new;
  end if;

  if (select private.is_admin()) then
    new.updated_at = now();
    return new;
  end if;

  raise exception 'Candidate updates must use the assessment attempt API';
end;
$$;

-- Supabase supports pg_cron. The sweep is idempotent and also runs
-- opportunistically from save/submit routes, so delayed scheduler execution
-- cannot extend an attempt.
create extension if not exists pg_cron with schema pg_catalog;

do $$
declare
  existing_job bigint;
begin
  select jobid into existing_job
  from cron.job
  where jobname = 'phase4-auto-submit-expired-attempts';

  if existing_job is not null then
    perform cron.unschedule(existing_job);
  end if;

  perform cron.schedule(
    'phase4-auto-submit-expired-attempts',
    '10 seconds',
    'select public.auto_submit_expired_attempts();'
  );
end;
$$;
