grant execute on function public.start_exam_attempt_internal(bigint, uuid, text) to service_role;

create or replace function public.save_exam_answer_internal(
  p_attempt_id uuid,
  p_student_id uuid,
  p_email text,
  p_question_id bigint,
  p_response_text text,
  p_response_url text,
  p_file_path text,
  p_file_name text,
  p_file_size bigint,
  p_client_revision bigint
)
returns table (
  saved boolean,
  attempt_status text,
  ends_at timestamptz,
  server_time timestamptz,
  saved_at timestamptz
)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_attempt public.exam_attempts;
  v_candidate public.candidates;
  v_question public.assessment_questions;
  v_now timestamptz := clock_timestamp();
  v_saved_at timestamptz;
begin
  select *
  into v_attempt
  from public.exam_attempts
  where id = p_attempt_id
  for update;

  if not found or v_attempt.student_id is distinct from p_student_id then
    raise exception 'Attempt not found';
  end if;

  if p_client_revision < 0 then
    raise exception 'Invalid answer revision';
  end if;

  select *
  into v_candidate
  from public.candidates
  where id = v_attempt.candidate_id;

  if lower(v_candidate.email) <> lower(trim(p_email))
    or v_candidate.auth_user_id is distinct from p_student_id
    or v_candidate.is_active is not true
    or (v_candidate.access_expires_at is not null and v_candidate.access_expires_at <= v_now)
  then
    raise exception 'Candidate assignment is unavailable';
  end if;

  if v_attempt.status <> 'in_progress' or v_now >= v_attempt.ends_at then
    if v_attempt.status = 'in_progress' then
      v_attempt := public.finalize_exam_attempt_internal(v_attempt.id, 'timeout');
    end if;
    return query select false, v_attempt.status, v_attempt.ends_at, v_now, null::timestamptz;
    return;
  end if;

  select *
  into v_question
  from public.assessment_questions
  where id = p_question_id
    and assessment_id = v_attempt.assessment_id;

  if not found then
    raise exception 'Question is not part of this assessment';
  end if;

  if v_question.response_type = 'written' then
    if nullif(trim(coalesce(p_response_url, '')), '') is not null or p_file_path is not null then
      raise exception 'Invalid written response';
    end if;
    if v_question.word_limit is not null
      and cardinality(regexp_split_to_array(nullif(trim(coalesce(p_response_text, '')), ''), '\s+')) > v_question.word_limit
    then
      raise exception 'Written response exceeds the word limit';
    end if;
  elsif v_question.response_type = 'link' then
    if nullif(trim(coalesce(p_response_text, '')), '') is not null or p_file_path is not null then
      raise exception 'Invalid link response';
    end if;
    if nullif(trim(coalesce(p_response_url, '')), '') is not null
      and trim(p_response_url) !~* '^https?://[^\s]+$'
    then
      raise exception 'Enter a valid http or https URL';
    end if;
  elsif v_question.response_type = 'file_upload' then
    if nullif(trim(coalesce(p_response_text, '')), '') is not null
      or nullif(trim(coalesce(p_response_url, '')), '') is not null
    then
      raise exception 'Invalid file response';
    end if;
    if p_file_path is not null
      and p_file_path not like (p_student_id::text || '/' || v_candidate.id::text || '/%')
    then
      raise exception 'Invalid file path';
    end if;
    if (p_file_path is null) <> (p_file_name is null)
      or (p_file_path is null) <> (p_file_size is null)
    then
      raise exception 'Incomplete file response';
    end if;
    if p_file_size is not null
      and p_file_size > coalesce(v_question.maximum_file_size_mb, 10)::bigint * 1024 * 1024
    then
      raise exception 'File is too large';
    end if;
    if p_file_name is not null
      and cardinality(v_question.allowed_file_types) > 0
      and not exists (
        select 1
        from unnest(v_question.allowed_file_types) as allowed(extension)
        where lower(trim(leading '.' from allowed.extension))
          = lower(regexp_replace(p_file_name, '^.*\.', ''))
      )
    then
      raise exception 'File type is not allowed';
    end if;
  else
    raise exception 'Unsupported response type';
  end if;

  insert into public.candidate_responses(
    attempt_id,
    candidate_id,
    question_id,
    response_text,
    response_url,
    file_path,
    file_name,
    file_size,
    client_revision,
    updated_at
  )
  values (
    v_attempt.id,
    v_attempt.candidate_id,
    v_question.id,
    nullif(trim(coalesce(p_response_text, '')), ''),
    nullif(trim(coalesce(p_response_url, '')), ''),
    p_file_path,
    p_file_name,
    p_file_size,
    p_client_revision,
    v_now
  )
  on conflict (candidate_id, question_id)
  do update set
    attempt_id = excluded.attempt_id,
    response_text = excluded.response_text,
    response_url = excluded.response_url,
    file_path = excluded.file_path,
    file_name = excluded.file_name,
    file_size = excluded.file_size,
    client_revision = excluded.client_revision,
    updated_at = excluded.updated_at
  where excluded.client_revision >= public.candidate_responses.client_revision
  returning updated_at into v_saved_at;

  if v_saved_at is not null then
    perform set_config('app.phase4_internal', 'on', true);
    update public.candidates
    set last_saved_at = v_saved_at, updated_at = v_saved_at
    where id = v_attempt.candidate_id;
  end if;

  return query select true, v_attempt.status, v_attempt.ends_at, v_now, v_saved_at;
end;
$$;

