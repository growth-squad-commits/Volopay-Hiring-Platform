  ends_at,
  submitted_at,
  status,
  submission_reason
)
select
  c.id,
  c.assessment_id,
  c.auth_user_id,
  coalesce(c.started_at, c.submitted_at - interval '1 minute'),
  greatest(
    coalesce(c.started_at, c.submitted_at - interval '1 minute') + interval '1 second',
    coalesce(
      c.expires_at,
      c.submitted_at,
      coalesce(c.started_at, c.submitted_at - interval '1 minute') + interval '1 minute'
    )
  ),
  case
    when c.status in ('submitted', 'reviewed') then coalesce(c.submitted_at, c.last_saved_at, c.started_at)
    else null
  end,
  case
    when c.status in ('submitted', 'reviewed') then 'submitted'
    else 'in_progress'
  end,
  case when c.status in ('submitted', 'reviewed') then 'manual' else null end
from public.candidates c
where c.auth_user_id is not null
  and (c.started_at is not null or c.submitted_at is not null)
on conflict (candidate_id) do nothing;

