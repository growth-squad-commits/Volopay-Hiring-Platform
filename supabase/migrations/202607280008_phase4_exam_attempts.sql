create or replace function public.submit_exam_attempt_internal(
  p_attempt_id uuid,
  p_student_id uuid,
  p_email text
)
returns table (
  attempt_status text,
  submitted_at timestamptz,
  ends_at timestamptz,
  server_time timestamptz
)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_attempt public.exam_attempts;
  v_candidate public.candidates;
  v_now timestamptz := clock_timestamp();
  v_missing integer;
  v_reason text;
begin
  select *
  into v_attempt
  from public.exam_attempts
  where id = p_attempt_id
  for update;

  if not found or v_attempt.student_id is distinct from p_student_id then
    raise exception 'Attempt not found';
  end if;

  select *
  into v_candidate
  from public.candidates
  where id = v_attempt.candidate_id;

  if lower(v_candidate.email) <> lower(trim(p_email))
    or v_candidate.auth_user_id is distinct from p_student_id
  then
    raise exception 'Candidate assignment is unavailable';
  end if;

  if v_attempt.status <> 'in_progress' then
    return query select v_attempt.status, v_attempt.submitted_at, v_attempt.ends_at, v_now;
    return;
  end if;

  v_reason := case when v_now >= v_attempt.ends_at then 'timeout' else 'manual' end;

  if v_reason = 'manual' then
    select count(*)
    into v_missing
    from public.assessment_questions q
    where q.assessment_id = v_attempt.assessment_id
      and q.is_required
      and not exists (
        select 1
        from public.candidate_responses r
        where r.attempt_id = v_attempt.id
          and r.question_id = q.id
          and case q.response_type
            when 'written' then nullif(trim(coalesce(r.response_text, '')), '') is not null
            when 'link' then nullif(trim(coalesce(r.response_url, '')), '') is not null
            when 'file_upload' then r.file_path is not null
            else false
          end
      );

    if v_missing > 0 then
      raise exception 'Complete % required task(s)', v_missing;
    end if;
  end if;

  v_attempt := public.finalize_exam_attempt_internal(v_attempt.id, v_reason);
  return query select v_attempt.status, v_attempt.submitted_at, v_attempt.ends_at, v_now;
end;
$$;

